struct Builder<'a> {
    n: &'a Names,
    out: Vec<Change>,
}

impl Builder<'_> {
    #[allow(clippy::too_many_arguments)]
    fn push(
        &mut self,
        phase: Phase,
        object_type: ObjectType,
        action: ChangeAction,
        object: String,
        sql: String,
        down_sql: Option<String>,
        destructive: bool,
        notes: Vec<String>,
        before: Option<String>,
        after: Option<String>,
    ) {
        self.out.push(Change {
            phase,
            object_type,
            action,
            object,
            sql,
            down_sql,
            destructive,
            notes,
            before,
            after,
        });
    }
}

fn by_name<T, K: std::hash::Hash + Eq>(items: &[T], key: impl Fn(&T) -> K) -> HashMap<K, &T> {
    items.iter().map(|i| (key(i), i)).collect()
}

/// Changes that make `target` match `source`. SQL refers to objects in
/// `target.schema`.
pub fn diff(source: &Snapshot, target: &Snapshot) -> (Vec<Change>, Vec<String>) {
    let names = Names::new(&target.schema);
    let n = &names;
    let mut b = Builder { n, out: Vec::new() };
    let mut hints = Vec::new();

    if !target.exists {
        b.push(
            Phase::CreateSchema,
            ObjectType::Schema,
            ChangeAction::Create,
            target.schema.clone(),
            format!("CREATE SCHEMA {};", n.schema),
            Some(format!("DROP SCHEMA {};", n.schema)),
            false,
            vec![],
            None,
            None,
        );
    }

    diff_enums(&mut b, source, target);
    diff_domains(&mut b, source, target);
    diff_sequences(&mut b, source, target);
    diff_tables(&mut b, source, target, &mut hints);
    diff_views(&mut b, source, target);
    diff_functions(&mut b, source, target);
    diff_triggers(&mut b, source, target);

    let mut changes = b.out;
    // Stable: within a phase, source order is kept (dependencies first).
    changes.sort_by_key(|c| c.phase);
    (changes, hints)
}

fn diff_enums(b: &mut Builder, source: &Snapshot, target: &Snapshot) {
    let n = b.n;
    let theirs = by_name(&target.enums, |e| e.name.clone());
    let ours = by_name(&source.enums, |e| e.name.clone());
    for e in &source.enums {
        match theirs.get(&e.name) {
            None => b.push(
                Phase::CreateType,
                ObjectType::Type,
                ChangeAction::Create,
                e.name.clone(),
                enum_sql(n, e),
                Some(format!("DROP TYPE {};", n.q(&e.name))),
                false,
                vec![],
                None,
                Some(e.labels.join(", ")),
            ),
            Some(t) if t.labels != e.labels => {
                // Additions keep existing labels in order: ALTER TYPE ADD VALUE.
                let kept: Vec<&String> = e.labels.iter().filter(|l| t.labels.contains(l)).collect();
                let additive = t.labels.iter().all(|l| e.labels.contains(l))
                    && kept.iter().copied().eq(t.labels.iter());
                let before = Some(t.labels.join(", "));
                let after = Some(e.labels.join(", "));
                if additive {
                    let mut stmts = Vec::new();
                    for (i, label) in e.labels.iter().enumerate() {
                        if t.labels.contains(label) {
                            continue;
                        }
                        let position =
                            match e.labels[..i].iter().rev().find(|l| t.labels.contains(l)) {
                                Some(prev) => format!(" AFTER {}", quote_literal(prev)),
                                None => {
                                    match e.labels[i + 1..].iter().find(|l| t.labels.contains(l)) {
                                        Some(next) => format!(" BEFORE {}", quote_literal(next)),
                                        None => String::new(),
                                    }
                                }
                            };
                        stmts.push(format!(
                            "ALTER TYPE {} ADD VALUE IF NOT EXISTS {}{position};",
                            n.q(&e.name),
                            quote_literal(label)
                        ));
                    }
                    b.push(
                        Phase::CreateType,
                        ObjectType::Type,
                        ChangeAction::Alter,
                        e.name.clone(),
                        join(&stmts),
                        None,
                        false,
                        vec![
                            "New enum values cannot be used in the same transaction that adds them."
                                .into(),
                            "Enum values cannot be removed, so this is not reversible.".into(),
                        ],
                        before,
                        after,
                    );
                } else {
                    b.push(
                        Phase::CreateType,
                        ObjectType::Type,
                        ChangeAction::Alter,
                        e.name.clone(),
                        format!(
                            "-- Enum {} lost or reordered values; PostgreSQL cannot remove them.\n\
                             -- Recreate the type and convert the columns that use it by hand.",
                            n.q(&e.name)
                        ),
                        None,
                        true,
                        vec!["Needs a hand-written migration.".into()],
                        before,
                        after,
                    );
                }
            }
            Some(_) => {}
        }
    }
    for e in &target.enums {
        if !ours.contains_key(&e.name) {
            b.push(
                Phase::DropType,
                ObjectType::Type,
                ChangeAction::Drop,
                e.name.clone(),
                format!("DROP TYPE {};", n.q(&e.name)),
                Some(enum_sql(n, e)),
                true,
                vec!["Fails while columns still use the type.".into()],
                Some(e.labels.join(", ")),
                None,
            );
        }
    }
}

fn diff_domains(b: &mut Builder, source: &Snapshot, target: &Snapshot) {
    let n = b.n;
    let create = |d: &DomainDef| format!("CREATE DOMAIN {} AS {};", n.q(&d.name), d.definition);
    let theirs = by_name(&target.domains, |d| d.name.clone());
    let ours = by_name(&source.domains, |d| d.name.clone());
    for d in &source.domains {
        match theirs.get(&d.name) {
            None => b.push(
                Phase::CreateType,
                ObjectType::Type,
                ChangeAction::Create,
                d.name.clone(),
                create(d),
                Some(format!("DROP DOMAIN {};", n.q(&d.name))),
                false,
                vec![],
                None,
                Some(d.definition.clone()),
            ),
            Some(t) if t.definition != d.definition => b.push(
                Phase::CreateType,
                ObjectType::Type,
                ChangeAction::Alter,
                d.name.clone(),
                format!(
                    "-- Domain {} changed; adjust it with ALTER DOMAIN by hand.",
                    n.q(&d.name)
                ),
                None,
                true,
                vec!["Needs a hand-written migration.".into()],
                Some(t.definition.clone()),
                Some(d.definition.clone()),
            ),
            Some(_) => {}
        }
    }
    for d in &target.domains {
        if !ours.contains_key(&d.name) {
            b.push(
                Phase::DropType,
                ObjectType::Type,
                ChangeAction::Drop,
                d.name.clone(),
                format!("DROP DOMAIN {};", n.q(&d.name)),
                Some(create(d)),
                true,
                vec!["Fails while columns still use the domain.".into()],
                Some(d.definition.clone()),
                None,
            );
        }
    }
}

fn diff_sequences(b: &mut Builder, source: &Snapshot, target: &Snapshot) {
    let n = b.n;
    let theirs = by_name(&target.sequences, |s| s.name.clone());
    let ours = by_name(&source.sequences, |s| s.name.clone());
    let owner_sql = |s: &SequenceDef| match &s.owned_by {
        Some([table, column]) => format!(
            "ALTER SEQUENCE {} OWNED BY {}.{};",
            n.q(&s.name),
            n.q(table),
            quote_ident(column)
        ),
        None => format!("ALTER SEQUENCE {} OWNED BY NONE;", n.q(&s.name)),
    };
    for s in &source.sequences {
        let existing = theirs.get(&s.name);
        match existing {
            None => b.push(
                Phase::CreateSequence,
                ObjectType::Sequence,
                ChangeAction::Create,
                s.name.clone(),
                format!(
                    "CREATE SEQUENCE {} {} START WITH {};",
                    n.q(&s.name),
                    sequence_options(s),
                    s.start
                ),
                Some(format!("DROP SEQUENCE {};", n.q(&s.name))),
                false,
                vec![],
                None,
                Some(sequence_options(s)),
            ),
            Some(t) if sequence_options(t) != sequence_options(s) => b.push(
                Phase::CreateSequence,
                ObjectType::Sequence,
                ChangeAction::Alter,
                s.name.clone(),
                format!("ALTER SEQUENCE {} {};", n.q(&s.name), sequence_options(s)),
                Some(format!(
                    "ALTER SEQUENCE {} {};",
                    n.q(&s.name),
                    sequence_options(t)
                )),
                false,
                vec![],
                Some(sequence_options(t)),
                Some(sequence_options(s)),
            ),
            Some(_) => {}
        }
        if s.owned_by.is_some() && existing.map(|t| &t.owned_by) != Some(&s.owned_by) {
            b.push(
                Phase::SequenceOwner,
                ObjectType::Sequence,
                ChangeAction::Alter,
                s.name.clone(),
                owner_sql(s),
                existing.map(|t| owner_sql(t)),
                false,
                vec![],
                None,
                None,
            );
        }
    }
    for s in &target.sequences {
        if !ours.contains_key(&s.name) {
            b.push(
                Phase::DropSequence,
                ObjectType::Sequence,
                ChangeAction::Drop,
                s.name.clone(),
                format!("DROP SEQUENCE {};", n.q(&s.name)),
                None,
                true,
                vec!["The sequence's current value is lost.".into()],
                Some(sequence_options(s)),
                None,
            );
        }
    }
}

fn diff_tables(b: &mut Builder, source: &Snapshot, target: &Snapshot, hints: &mut Vec<String>) {
    let n = b.n;
    let theirs = by_name(&target.tables, |t| t.name.clone());
    let ours = by_name(&source.tables, |t| t.name.clone());

    for t in &source.tables {
        let Some(existing) = theirs.get(&t.name) else {
            b.push(
                Phase::CreateTable,
                ObjectType::Table,
                ChangeAction::Create,
                t.name.clone(),
                create_table_sql(n, t),
                Some(format!("DROP TABLE {};", n.q(&t.name))),
                false,
                vec![],
                None,
                Some(create_table_sql(n, t)),
            );
            for c in &t.constraints {
                add_constraint(b, &t.name, c, None);
            }
            for i in &t.indexes {
                create_index(b, &t.name, i, None);
            }
            continue;
        };
        diff_columns(b, t, existing, hints);
        if t.partition_key != existing.partition_key {
            b.push(
                Phase::AlterColumn,
                ObjectType::Table,
                ChangeAction::Alter,
                t.name.clone(),
                format!(
                    "-- Partitioning of {} differs; it cannot be changed in place.",
                    n.q(&t.name)
                ),
                None,
                true,
                vec!["Needs a hand-written migration.".into()],
                existing.partition_key.clone(),
                t.partition_key.clone(),
            );
        }

        let their_cons = by_name(&existing.constraints, |c| c.name.clone());
        let our_cons = by_name(&t.constraints, |c| c.name.clone());
        for c in &t.constraints {
            match their_cons.get(&c.name) {
                None => add_constraint(b, &t.name, c, None),
                Some(old) if old.definition != c.definition || old.kind != c.kind => {
                    drop_constraint(b, &t.name, old);
                    add_constraint(b, &t.name, c, Some(old));
                }
                Some(_) => {}
            }
        }
        for c in &existing.constraints {
            if !our_cons.contains_key(&c.name) {
                drop_constraint(b, &t.name, c);
            }
        }

        let their_ix = by_name(&existing.indexes, |i| i.name.clone());
        let our_ix = by_name(&t.indexes, |i| i.name.clone());
        for i in &t.indexes {
            match their_ix.get(&i.name) {
                None => create_index(b, &t.name, i, None),
                Some(old) if old.definition != i.definition => {
                    drop_index(b, &t.name, old);
                    create_index(b, &t.name, i, Some(old));
                }
                Some(_) => {}
            }
        }
        for i in &existing.indexes {
            if !our_ix.contains_key(&i.name) {
                drop_index(b, &t.name, i);
            }
        }
    }

    let dropped: Vec<&TableDef> = target
        .tables
        .iter()
        .filter(|t| !ours.contains_key(&t.name))
        .collect();
    for t in &dropped {
        b.push(
            Phase::DropTable,
            ObjectType::Table,
            ChangeAction::Drop,
            t.name.clone(),
            format!("DROP TABLE {};", n.q(&t.name)),
            None,
            true,
            vec!["All rows in the table are deleted.".into()],
            Some(create_table_sql(n, t)),
            None,
        );
    }
    // A dropped table and a created one with the same columns: likely a rename.
    let column_set = |t: &TableDef| -> Vec<(String, String)> {
        let mut cols: Vec<_> = t
            .columns
            .iter()
            .map(|c| (c.name.clone(), c.data_type.clone()))
            .collect();
        cols.sort();
        cols
    };
    for old in &dropped {
        for new in source
            .tables
            .iter()
            .filter(|t| !theirs.contains_key(&t.name))
        {
            if !old.columns.is_empty() && column_set(old) == column_set(new) {
                hints.push(format!(
                    "Table {} may be {} renamed. Instead of dropping and creating it, consider: ALTER TABLE {} RENAME TO {};",
                    new.name,
                    old.name,
                    n.q(&old.name),
                    quote_ident(&new.name)
                ));
            }
        }
    }
}

fn diff_columns(b: &mut Builder, t: &TableDef, existing: &TableDef, hints: &mut Vec<String>) {
    let n = b.n;
    let table = n.q(&t.name);
    let theirs = by_name(&existing.columns, |c| c.name.clone());
    let ours = by_name(&t.columns, |c| c.name.clone());
    let mut added = Vec::new();

    for c in &t.columns {
        let object = format!("{}.{}", t.name, c.name);
        let Some(old) = theirs.get(&c.name) else {
            let mut notes = Vec::new();
            if c.not_null && c.default.is_none() && c.identity.is_none() && c.generated.is_none() {
                notes.push("Fails if the table has rows: add a default or backfill first.".into());
            }
            b.push(
                Phase::AlterColumn,
                ObjectType::Column,
                ChangeAction::Create,
                object,
                format!("ALTER TABLE {table} ADD COLUMN {};", column_sql(c)),
                Some(format!(
                    "ALTER TABLE {table} DROP COLUMN {};",
                    quote_ident(&c.name)
                )),
                false,
                notes,
                None,
                Some(column_sql(c)),
            );
            added.push(c);
            continue;
        };
        if *old == c {
            continue;
        }
        let col = quote_ident(&c.name);
        let before = Some(column_sql(old));
        let after = Some(column_sql(c));
        if old.identity != c.identity || old.generated != c.generated {
            b.push(
                Phase::AlterColumn,
                ObjectType::Column,
                ChangeAction::Alter,
                object,
                format!(
                    "ALTER TABLE {table} DROP COLUMN {col};\nALTER TABLE {table} ADD COLUMN {};",
                    column_sql(c)
                ),
                None,
                true,
                vec!["Identity or generation changed: the column is recreated and its values are lost.".into()],
                before,
                after,
            );
            continue;
        }
        let mut up = Vec::new();
        let mut down = Vec::new();
        let mut notes = Vec::new();
        let mut destructive = false;
        if old.data_type != c.data_type {
            up.push(format!(
                "ALTER TABLE {table} ALTER COLUMN {col} TYPE {} USING {col}::{};",
                c.data_type, c.data_type
            ));
            down.push(format!(
                "ALTER TABLE {table} ALTER COLUMN {col} TYPE {} USING {col}::{};",
                old.data_type, old.data_type
            ));
            if !is_widening(&old.data_type, &c.data_type) {
                destructive = true;
                notes.push(format!(
                    "{} to {} may fail or lose data.",
                    old.data_type, c.data_type
                ));
            }
        }
        if old.default != c.default {
            up.push(match &c.default {
                Some(d) => format!("ALTER TABLE {table} ALTER COLUMN {col} SET DEFAULT {d};"),
                None => format!("ALTER TABLE {table} ALTER COLUMN {col} DROP DEFAULT;"),
            });
            down.push(match &old.default {
                Some(d) => format!("ALTER TABLE {table} ALTER COLUMN {col} SET DEFAULT {d};"),
                None => format!("ALTER TABLE {table} ALTER COLUMN {col} DROP DEFAULT;"),
            });
        }
        if old.not_null != c.not_null {
            if c.not_null {
                up.push(format!(
                    "ALTER TABLE {table} ALTER COLUMN {col} SET NOT NULL;"
                ));
                down.push(format!(
                    "ALTER TABLE {table} ALTER COLUMN {col} DROP NOT NULL;"
                ));
                notes.push("Fails while the column contains NULLs.".into());
            } else {
                up.push(format!(
                    "ALTER TABLE {table} ALTER COLUMN {col} DROP NOT NULL;"
                ));
                down.push(format!(
                    "ALTER TABLE {table} ALTER COLUMN {col} SET NOT NULL;"
                ));
            }
        }
        down.reverse();
        b.push(
            Phase::AlterColumn,
            ObjectType::Column,
            ChangeAction::Alter,
            object,
            join(&up),
            Some(join(&down)),
            destructive,
            notes,
            before,
            after,
        );
    }
    for c in &existing.columns {
        if ours.contains_key(&c.name) {
            continue;
        }
        if let Some(new) = added.iter().find(|a| a.data_type == c.data_type) {
            hints.push(format!(
                "Column {}.{} may be {} renamed. Consider: ALTER TABLE {table} RENAME COLUMN {} TO {};",
                t.name,
                new.name,
                c.name,
                quote_ident(&c.name),
                quote_ident(&new.name)
            ));
        }
        b.push(
            Phase::DropColumn,
            ObjectType::Column,
            ChangeAction::Drop,
            format!("{}.{}", t.name, c.name),
            format!("ALTER TABLE {table} DROP COLUMN {};", quote_ident(&c.name)),
            None,
            true,
            vec!["The column's values are lost.".into()],
            Some(column_sql(c)),
            None,
        );
    }
}

fn add_constraint(
    b: &mut Builder,
    table: &str,
    c: &ConstraintDef,
    replaced: Option<&ConstraintDef>,
) {
    let n = b.n;
    let mut notes = Vec::new();
    if c.kind == "f" || c.kind == "c" {
        notes.push("Fails if existing rows violate it.".into());
    }
    b.push(
        if c.kind == "f" {
            Phase::AddForeignKey
        } else {
            Phase::AddConstraint
        },
        ObjectType::Constraint,
        if replaced.is_some() {
            ChangeAction::Alter
        } else {
            ChangeAction::Create
        },
        format!("{table}.{}", c.name),
        add_constraint_sql(n, table, c),
        Some(drop_constraint_sql(n, table, c)),
        false,
        notes,
        replaced.map(|r| r.definition.clone()),
        Some(c.definition.clone()),
    );
}

fn drop_constraint(b: &mut Builder, table: &str, c: &ConstraintDef) {
    let n = b.n;
    b.push(
        if c.kind == "f" {
            Phase::DropForeignKey
        } else {
            Phase::DropConstraint
        },
        ObjectType::Constraint,
        ChangeAction::Drop,
        format!("{table}.{}", c.name),
        drop_constraint_sql(n, table, c),
        Some(add_constraint_sql(n, table, c)),
        false,
        vec![],
        Some(c.definition.clone()),
        None,
    );
}

fn create_index(b: &mut Builder, table: &str, i: &IndexDef, replaced: Option<&IndexDef>) {
    let n = b.n;
    b.push(
        Phase::CreateIndex,
        ObjectType::Index,
        if replaced.is_some() {
            ChangeAction::Alter
        } else {
            ChangeAction::Create
        },
        format!("{table}.{}", i.name),
        index_sql(i),
        Some(format!("DROP INDEX {};", n.q(&i.name))),
        false,
        vec!["Locks writes to the table while the index builds.".into()],
        replaced.map(|r| r.definition.clone()),
        Some(i.definition.clone()),
    );
}

fn drop_index(b: &mut Builder, table: &str, i: &IndexDef) {
    let n = b.n;
    b.push(
        Phase::DropIndex,
        ObjectType::Index,
        ChangeAction::Drop,
        format!("{table}.{}", i.name),
        format!("DROP INDEX {};", n.q(&i.name)),
        Some(index_sql(i)),
        false,
        vec![],
        Some(i.definition.clone()),
        None,
    );
}

fn diff_views(b: &mut Builder, source: &Snapshot, target: &Snapshot) {
    let n = b.n;
    let theirs = by_name(&target.views, |v| v.name.clone());
    let ours = by_name(&source.views, |v| v.name.clone());
    for v in &source.views {
        match theirs.get(&v.name) {
            None => b.push(
                Phase::CreateView,
                ObjectType::View,
                ChangeAction::Create,
                v.name.clone(),
                view_sql(n, v, false),
                Some(drop_view_sql(n, v)),
                false,
                vec![],
                None,
                Some(v.definition.clone()),
            ),
            Some(old) if old.definition != v.definition || old.materialized != v.materialized => {
                let replaceable = !v.materialized && !old.materialized;
                let (sql, down, notes) = if replaceable {
                    (
                        view_sql(n, v, true),
                        view_sql(n, old, true),
                        vec!["CREATE OR REPLACE VIEW fails if existing columns change type or order.".into()],
                    )
                } else {
                    (
                        format!("{}\n{}", drop_view_sql(n, old), view_sql(n, v, false)),
                        format!("{}\n{}", drop_view_sql(n, v), view_sql(n, old, false)),
                        vec!["The view is dropped and recreated; grants on it are lost.".into()],
                    )
                };
                b.push(
                    Phase::CreateView,
                    ObjectType::View,
                    ChangeAction::Alter,
                    v.name.clone(),
                    sql,
                    Some(down),
                    false,
                    notes,
                    Some(old.definition.clone()),
                    Some(v.definition.clone()),
                );
            }
            Some(_) => {}
        }
    }
    for v in target.views.iter().rev() {
        if !ours.contains_key(&v.name) {
            b.push(
                Phase::DropView,
                ObjectType::View,
                ChangeAction::Drop,
                v.name.clone(),
                drop_view_sql(n, v),
                Some(view_sql(n, v, false)),
                v.materialized,
                vec![],
                Some(v.definition.clone()),
                None,
            );
        }
    }
}

fn diff_functions(b: &mut Builder, source: &Snapshot, target: &Snapshot) {
    let n = b.n;
    let key = |f: &FunctionDef| (f.name.clone(), f.arguments.clone());
    let theirs = by_name(&target.functions, key);
    let ours: HashSet<(String, String)> = source.functions.iter().map(key).collect();
    for f in &source.functions {
        let object = format!("{}({})", f.name, f.arguments);
        match theirs.get(&key(f)) {
            None => b.push(
                Phase::CreateFunction,
                ObjectType::Function,
                ChangeAction::Create,
                object,
                function_sql(f),
                Some(drop_function_sql(n, f)),
                false,
                vec![],
                None,
                Some(f.definition.clone()),
            ),
            Some(old) if old.definition != f.definition => b.push(
                Phase::CreateFunction,
                ObjectType::Function,
                ChangeAction::Alter,
                object,
                function_sql(f),
                Some(function_sql(old)),
                false,
                vec!["CREATE OR REPLACE fails if the result type changed.".into()],
                Some(old.definition.clone()),
                Some(f.definition.clone()),
            ),
            Some(_) => {}
        }
    }
    for f in &target.functions {
        if !ours.contains(&key(f)) {
            b.push(
                Phase::DropFunction,
                ObjectType::Function,
                ChangeAction::Drop,
                format!("{}({})", f.name, f.arguments),
                drop_function_sql(n, f),
                Some(function_sql(f)),
                false,
                vec![],
                Some(f.definition.clone()),
                None,
            );
        }
    }
}

fn diff_triggers(b: &mut Builder, source: &Snapshot, target: &Snapshot) {
    let n = b.n;
    let key = |t: &TriggerDef| (t.table.clone(), t.name.clone());
    let theirs = by_name(&target.triggers, key);
    let ours: HashSet<(String, String)> = source.triggers.iter().map(key).collect();
    for t in &source.triggers {
        let object = format!("{}.{}", t.table, t.name);
        match theirs.get(&key(t)) {
            None => b.push(
                Phase::CreateTrigger,
                ObjectType::Trigger,
                ChangeAction::Create,
                object,
                trigger_sql(t),
                Some(drop_trigger_sql(n, t)),
                false,
                vec![],
                None,
                Some(t.definition.clone()),
            ),
            Some(old) if old.definition != t.definition => b.push(
                Phase::CreateTrigger,
                ObjectType::Trigger,
                ChangeAction::Alter,
                object,
                format!("{}\n{}", drop_trigger_sql(n, old), trigger_sql(t)),
                Some(format!("{}\n{}", drop_trigger_sql(n, t), trigger_sql(old))),
                false,
                vec![],
                Some(old.definition.clone()),
                Some(t.definition.clone()),
            ),
            Some(_) => {}
        }
    }
    for t in &target.triggers {
        if !ours.contains(&key(t)) {
            b.push(
                Phase::DropTrigger,
                ObjectType::Trigger,
                ChangeAction::Drop,
                format!("{}.{}", t.table, t.name),
                drop_trigger_sql(n, t),
                Some(trigger_sql(t)),
                false,
                vec![],
                Some(t.definition.clone()),
                None,
            );
        }
    }
}

/// Settings placed before the generated statements: unqualified names in
/// copied definitions resolve to the target schema, and function bodies are
/// not validated against objects created later in the same script.
pub fn preamble(target_schema: &str) -> String {
    format!(
        "SET LOCAL search_path = {};\nSET LOCAL check_function_bodies = off;",
        quote_ident(target_schema)
    )
}

/// Script of the given changes (in order) with the preamble.
pub fn script(target_schema: &str, changes: &[&Change]) -> String {
    let mut out = preamble(target_schema);
    for c in changes {
        out.push_str("\n\n");
        out.push_str(&c.sql);
    }
    out.push('\n');
    out
}

