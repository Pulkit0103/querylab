//! Schema comparison: loads a snapshot of one schema from each side, works
//! out the changes that turn the target into the source and renders them as
//! SQL (with inverse statements where possible).
//!
//! Objects are matched by name. Definitions come from PostgreSQL's own
//! deparsers (`pg_get_constraintdef`, `pg_get_indexdef`, `pg_get_viewdef`,
//! `pg_get_functiondef`, `pg_get_triggerdef`), read with `search_path` set to
//! the schema being described, so same-schema references are unqualified and
//! resolve to the target schema when the script runs.

use std::collections::{HashMap, HashSet};

use sqlx::PgConnection;
use uuid::Uuid;

use crate::{
    errors::AppResult,
    models::schema_diff::{
        Change, ChangeAction, ColumnDef, ConstraintDef, DiffRequest, DiffResponse, DomainDef,
        EnumDef, FunctionDef, IndexDef, ObjectType, Phase, SequenceDef, Snapshot, TableDef,
        TriggerDef, ViewDef,
    },
    services::{
        schema::{close, SchemaService},
        sql_builder::{quote_ident, quote_literal},
        target_db,
    },
};

// ---------------------------------------------------------------------------
// SQL helpers
// ---------------------------------------------------------------------------

struct Names {
    schema: String,
}

impl Names {
    fn new(target_schema: &str) -> Self {
        Self {
            schema: quote_ident(target_schema),
        }
    }

    /// `schema.name` in the target.
    fn q(&self, name: &str) -> String {
        format!("{}.{}", self.schema, quote_ident(name))
    }
}

fn column_sql(c: &ColumnDef) -> String {
    let mut out = format!("{} {}", quote_ident(&c.name), c.data_type);
    if let Some(expr) = &c.generated {
        out.push_str(&format!(" GENERATED ALWAYS AS ({expr}) STORED"));
    } else if let Some(identity) = &c.identity {
        out.push_str(if identity == "always" {
            " GENERATED ALWAYS AS IDENTITY"
        } else {
            " GENERATED BY DEFAULT AS IDENTITY"
        });
    } else if let Some(default) = &c.default {
        out.push_str(&format!(" DEFAULT {default}"));
    }
    if c.not_null && c.identity.is_none() {
        out.push_str(" NOT NULL");
    }
    out
}

fn create_table_sql(n: &Names, t: &TableDef) -> String {
    let columns: Vec<String> = t
        .columns
        .iter()
        .map(|c| format!("    {}", column_sql(c)))
        .collect();
    let mut sql = format!(
        "CREATE TABLE {} (\n{}\n)",
        n.q(&t.name),
        columns.join(",\n")
    );
    if let Some(key) = &t.partition_key {
        sql.push_str(&format!(" PARTITION BY {key}"));
    }
    sql.push(';');
    sql
}

fn enum_sql(n: &Names, e: &EnumDef) -> String {
    let labels: Vec<String> = e.labels.iter().map(|l| quote_literal(l)).collect();
    format!(
        "CREATE TYPE {} AS ENUM ({});",
        n.q(&e.name),
        labels.join(", ")
    )
}

fn sequence_options(s: &SequenceDef) -> String {
    format!(
        "AS {} INCREMENT BY {} MINVALUE {} MAXVALUE {} {}",
        s.data_type,
        s.increment,
        s.min,
        s.max,
        if s.cycle { "CYCLE" } else { "NO CYCLE" }
    )
}

fn view_sql(n: &Names, v: &ViewDef, replace: bool) -> String {
    let kind = if v.materialized {
        "MATERIALIZED VIEW"
    } else if replace {
        "OR REPLACE VIEW"
    } else {
        "VIEW"
    };
    format!("CREATE {kind} {} AS\n{};", n.q(&v.name), v.definition)
}

fn drop_view_sql(n: &Names, v: &ViewDef) -> String {
    let kind = if v.materialized {
        "MATERIALIZED VIEW"
    } else {
        "VIEW"
    };
    format!("DROP {kind} {};", n.q(&v.name))
}

fn function_sql(f: &FunctionDef) -> String {
    format!("{};", f.definition.trim_end())
}

fn drop_function_sql(n: &Names, f: &FunctionDef) -> String {
    let kind = if f.kind == "procedure" {
        "PROCEDURE"
    } else {
        "FUNCTION"
    };
    format!("DROP {kind} {}({});", n.q(&f.name), f.arguments)
}

fn trigger_sql(t: &TriggerDef) -> String {
    format!("{};", t.definition.trim_end())
}

fn drop_trigger_sql(n: &Names, t: &TriggerDef) -> String {
    format!(
        "DROP TRIGGER {} ON {};",
        quote_ident(&t.name),
        n.q(&t.table)
    )
}

fn index_sql(i: &IndexDef) -> String {
    format!("{};", i.definition)
}

fn add_constraint_sql(n: &Names, table: &str, c: &ConstraintDef) -> String {
    format!(
        "ALTER TABLE {} ADD CONSTRAINT {} {};",
        n.q(table),
        quote_ident(&c.name),
        c.definition
    )
}

fn drop_constraint_sql(n: &Names, table: &str, c: &ConstraintDef) -> String {
    format!(
        "ALTER TABLE {} DROP CONSTRAINT {};",
        n.q(table),
        quote_ident(&c.name)
    )
}

fn join(statements: &[String]) -> String {
    statements.join("\n")
}

fn integer_rank(t: &str) -> Option<u8> {
    match t {
        "smallint" => Some(1),
        "integer" => Some(2),
        "bigint" => Some(3),
        _ => None,
    }
}

/// `name(a,b)` -> ("name", [a, b]).
fn typmods(t: &str) -> (&str, Vec<i64>) {
    match t.split_once('(') {
        Some((base, rest)) => (
            base.trim(),
            rest.trim_end_matches(')')
                .split(',')
                .filter_map(|p| p.trim().parse().ok())
                .collect(),
        ),
        None => (t.trim(), Vec::new()),
    }
}

/// Whether changing a column from `old` to `new` keeps every value.
pub fn is_widening(old: &str, new: &str) -> bool {
    if old == new {
        return true;
    }
    if let (Some(a), Some(b)) = (integer_rank(old), integer_rank(new)) {
        return b >= a;
    }
    let (ob, om) = typmods(old);
    let (nb, nm) = typmods(new);
    let textual = |b: &str| matches!(b, "text" | "character varying" | "character");
    match (ob, nb) {
        _ if integer_rank(old).is_some() && nb == "numeric" => {
            nm.is_empty() || {
                let (p, s) = (nm[0], nm.get(1).copied().unwrap_or(0));
                p - s >= 19
            }
        }
        ("real", "double precision") => true,
        ("numeric", "numeric") => {
            if nm.is_empty() {
                return true;
            }
            if om.is_empty() {
                return false;
            }
            let (op, os) = (om[0], om.get(1).copied().unwrap_or(0));
            let (np, ns) = (nm[0], nm.get(1).copied().unwrap_or(0));
            np - ns >= op - os && ns >= os
        }
        (o, "text") if textual(o) => true,
        (o, "character varying") if textual(o) => {
            nm.is_empty() || (!om.is_empty() && o != "text" && nm[0] >= om[0])
        }
        ("text", "character varying") => nm.is_empty(),
        _ => false,
    }
}

