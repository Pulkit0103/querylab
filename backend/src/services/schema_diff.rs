const NOT_FROM_EXTENSION: &str = "NOT EXISTS (SELECT 1 FROM pg_depend dep WHERE dep.objid = {oid} \
     AND dep.classid = '{catalog}'::regclass AND dep.deptype = 'e')";

fn not_from_extension(oid: &str, catalog: &str) -> String {
    NOT_FROM_EXTENSION
        .replace("{oid}", oid)
        .replace("{catalog}", catalog)
}

#[derive(sqlx::FromRow)]
struct TableRow {
    oid: i64,
    name: String,
    partition_key: Option<String>,
}

#[derive(sqlx::FromRow)]
struct ColumnRow {
    oid: i64,
    name: String,
    data_type: String,
    not_null: bool,
    default_expr: Option<String>,
    identity: Option<String>,
    generated: Option<String>,
}

#[derive(sqlx::FromRow)]
struct ConstraintRow {
    oid: i64,
    name: String,
    kind: String,
    definition: String,
}

#[derive(sqlx::FromRow)]
struct IndexRow {
    oid: i64,
    name: String,
    definition: String,
}

#[derive(sqlx::FromRow)]
struct FunctionRow {
    name: String,
    quoted_name: String,
    qualified: String,
    arguments: String,
    kind: String,
    definition: String,
}

#[derive(sqlx::FromRow)]
struct SequenceRow {
    name: String,
    data_type: String,
    start: i64,
    increment: i64,
    min: i64,
    max: i64,
    cycle: bool,
    owned_table: Option<String>,
    owned_column: Option<String>,
}

macro_rules! fetch {
    ($conn:expr, $ty:ty, $sql:expr, $($bind:expr),*) => {
        sqlx::query_as::<_, $ty>($sql)
            $(.bind($bind))*
            .fetch_all(&mut *$conn)
            .await
            .map_err(target_db::query_error)?
    };
}

/// Removes `schema.` qualifiers from a deparsed definition.
///
/// PostgreSQL qualifies names that are not visible on `search_path`: always
/// for `pg_get_indexdef` / `pg_get_triggerdef` tables, and for everything
/// when the role lacks USAGE on the schema (search_path then skips it).
/// Same-schema references are made unqualified so definitions compare
/// across schemas and resolve to the target when the script runs. Function
/// bodies are not passed through this.
pub fn unqualify(definition: &str, schema: &str) -> String {
    let needle = format!("{}.", quote_ident(schema));
    let mut out = String::with_capacity(definition.len());
    let mut rest = definition;
    while let Some(pos) = rest.find(&needle) {
        let previous = if pos > 0 {
            rest[..pos].chars().last()
        } else {
            out.chars().last()
        };
        let boundary =
            !matches!(previous, Some(c) if c.is_alphanumeric() || c == '_' || c == '$' || c == '"');
        out.push_str(&rest[..pos]);
        if !boundary {
            out.push_str(&needle);
        }
        rest = &rest[pos + needle.len()..];
    }
    out.push_str(rest);
    out
}

/// Reads one schema. Must run on a dedicated connection (it changes
/// `search_path`).
pub async fn load_snapshot(conn: &mut PgConnection, schema: &str) -> AppResult<Snapshot> {
    let exists: bool =
        sqlx::query_scalar("SELECT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = $1)")
            .bind(schema)
            .fetch_one(&mut *conn)
            .await
            .map_err(target_db::query_error)?;
    let mut snap = Snapshot {
        schema: schema.to_string(),
        exists,
        ..Default::default()
    };
    if !exists {
        return Ok(snap);
    }
    sqlx::query("SELECT set_config('search_path', quote_ident($1), false)")
        .bind(schema)
        .execute(&mut *conn)
        .await
        .map_err(target_db::query_error)?;

    let tables = fetch!(
        conn,
        TableRow,
        &format!(
            "SELECT c.oid::bigint AS oid, c.relname::text AS name, \
                    CASE WHEN c.relkind = 'p' THEN pg_get_partkeydef(c.oid) END AS partition_key \
             FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace \
             WHERE n.nspname = $1 AND c.relkind IN ('r', 'p') AND NOT c.relispartition AND {} \
             ORDER BY c.oid",
            not_from_extension("c.oid", "pg_class")
        ),
        schema
    );
    let oids: Vec<i64> = tables.iter().map(|t| t.oid).collect();
    let columns = fetch!(
        conn,
        ColumnRow,
        "SELECT a.attrelid::bigint AS oid, a.attname::text AS name, \
                format_type(a.atttypid, a.atttypmod) AS data_type, a.attnotnull AS not_null, \
                CASE WHEN a.attgenerated = '' THEN pg_get_expr(d.adbin, d.adrelid) END AS default_expr, \
                CASE a.attidentity WHEN 'a' THEN 'always' WHEN 'd' THEN 'by_default' END AS identity, \
                CASE WHEN a.attgenerated <> '' THEN pg_get_expr(d.adbin, d.adrelid) END AS generated \
         FROM pg_attribute a \
         LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum \
         WHERE a.attrelid = ANY ($1::bigint[]::oid[]) AND a.attnum > 0 AND NOT a.attisdropped \
         ORDER BY a.attrelid, a.attnum",
        &oids
    );
    let constraints = fetch!(
        conn,
        ConstraintRow,
        "SELECT con.conrelid::bigint AS oid, con.conname::text AS name, con.contype::text AS kind, \
                pg_get_constraintdef(con.oid) AS definition \
         FROM pg_constraint con \
         WHERE con.conrelid = ANY ($1::bigint[]::oid[]) AND con.contype IN ('p', 'u', 'c', 'f', 'x') \
           AND con.conislocal \
         ORDER BY con.conrelid, CASE con.contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 ELSE 2 END, con.conname",
        &oids
    );
    let indexes = fetch!(
        conn,
        IndexRow,
        "SELECT i.indrelid::bigint AS oid, ic.relname::text AS name, pg_get_indexdef(i.indexrelid) AS definition \
         FROM pg_index i JOIN pg_class ic ON ic.oid = i.indexrelid \
         WHERE i.indrelid = ANY ($1::bigint[]::oid[]) \
           AND NOT EXISTS (SELECT 1 FROM pg_constraint con WHERE con.conindid = i.indexrelid \
                           AND con.conrelid = i.indrelid AND con.contype IN ('p', 'u', 'x')) \
         ORDER BY i.indrelid, ic.relname",
        &oids
    );

    let mut by_oid: HashMap<i64, TableDef> = tables
        .iter()
        .map(|t| {
            (
                t.oid,
                TableDef {
                    name: t.name.clone(),
                    partition_key: t.partition_key.clone(),
                    ..Default::default()
                },
            )
        })
        .collect();
    for c in columns {
        if let Some(t) = by_oid.get_mut(&c.oid) {
            t.columns.push(ColumnDef {
                name: c.name,
                data_type: unqualify(&c.data_type, schema),
                not_null: c.not_null,
                default: c.default_expr.map(|d| unqualify(&d, schema)),
                identity: c.identity,
                generated: c.generated.map(|g| unqualify(&g, schema)),
            });
        }
    }
    for c in constraints {
        if let Some(t) = by_oid.get_mut(&c.oid) {
            t.constraints.push(ConstraintDef {
                name: c.name,
                kind: c.kind,
                definition: unqualify(&c.definition, schema),
            });
        }
    }
    for i in indexes {
        if let Some(t) = by_oid.get_mut(&i.oid) {
            t.indexes.push(IndexDef {
                name: i.name,
                definition: unqualify(&i.definition, schema),
            });
        }
    }
    snap.tables = tables
        .iter()
        .filter_map(|t| by_oid.remove(&t.oid))
        .collect();

    snap.views = sqlx::query_as::<_, (String, bool, String)>(&format!(
        "SELECT c.relname::text, c.relkind = 'm', rtrim(btrim(pg_get_viewdef(c.oid, true)), ';') \
         FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace \
         WHERE n.nspname = $1 AND c.relkind IN ('v', 'm') AND {} ORDER BY c.oid",
        not_from_extension("c.oid", "pg_class")
    ))
    .bind(schema)
    .fetch_all(&mut *conn)
    .await
    .map_err(target_db::query_error)?
    .into_iter()
    .map(|(name, materialized, definition)| ViewDef {
        name,
        materialized,
        definition: unqualify(&definition, schema),
    })
    .collect();

    let functions = fetch!(
        conn,
        FunctionRow,
        &format!(
            "SELECT p.proname::text AS name, quote_ident(p.proname) AS quoted_name, \
                    format('%I.%I', n.nspname, p.proname) AS qualified, \
                    pg_get_function_identity_arguments(p.oid) AS arguments, \
                    CASE p.prokind WHEN 'p' THEN 'procedure' ELSE 'function' END AS kind, \
                    pg_get_functiondef(p.oid) AS definition \
             FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace \
             WHERE n.nspname = $1 AND p.prokind IN ('f', 'p') AND {} ORDER BY p.oid",
            not_from_extension("p.oid", "pg_proc")
        ),
        schema
    );
    snap.functions = functions
        .into_iter()
        .map(|f| FunctionDef {
            // The header is always schema-qualified; drop the schema so the
            // definition compares across schemas and lands in the target.
            definition: f.definition.replacen(
                &format!("{}(", f.qualified),
                &format!("{}(", f.quoted_name),
                1,
            ),
            name: f.name,
            arguments: f.arguments,
            kind: f.kind,
        })
        .collect();

    snap.triggers = sqlx::query_as::<_, (String, String, String)>(
        "SELECT c.relname::text, t.tgname::text, pg_get_triggerdef(t.oid) \
         FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid \
         WHERE t.tgrelid = ANY ($1::bigint[]::oid[]) AND NOT t.tgisinternal \
         ORDER BY c.relname, t.tgname",
    )
    .bind(&oids)
    .fetch_all(&mut *conn)
    .await
    .map_err(target_db::query_error)?
    .into_iter()
    .map(|(table, name, definition)| TriggerDef {
        table,
        name,
        definition: unqualify(&definition, schema),
    })
    .collect();

    snap.enums = sqlx::query_as::<_, (String, Vec<String>)>(&format!(
        "SELECT t.typname::text, ARRAY(SELECT e.enumlabel::text FROM pg_enum e \
                                        WHERE e.enumtypid = t.oid ORDER BY e.enumsortorder) \
         FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace \
         WHERE n.nspname = $1 AND t.typtype = 'e' AND {} ORDER BY t.oid",
        not_from_extension("t.oid", "pg_type")
    ))
    .bind(schema)
    .fetch_all(&mut *conn)
    .await
    .map_err(target_db::query_error)?
    .into_iter()
    .map(|(name, labels)| EnumDef { name, labels })
    .collect();

    snap.domains = sqlx::query_as::<_, (String, String)>(&format!(
        "SELECT t.typname::text, \
                format_type(t.typbasetype, t.typtypmod) \
                || COALESCE(' DEFAULT ' || t.typdefault, '') \
                || CASE WHEN t.typnotnull THEN ' NOT NULL' ELSE '' END \
                || COALESCE((SELECT ' ' || string_agg(pg_get_constraintdef(con.oid), ' ' ORDER BY con.conname) \
                             FROM pg_constraint con WHERE con.contypid = t.oid AND con.contype = 'c'), '') \
         FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace \
         WHERE n.nspname = $1 AND t.typtype = 'd' AND {} ORDER BY t.oid",
        not_from_extension("t.oid", "pg_type")
    ))
    .bind(schema)
    .fetch_all(&mut *conn)
    .await
    .map_err(target_db::query_error)?
    .into_iter()
    .map(|(name, definition)| DomainDef {
        name,
        definition: unqualify(&definition, schema),
    })
    .collect();

    let sequences = fetch!(
        conn,
        SequenceRow,
        &format!(
            "SELECT c.relname::text AS name, format_type(s.seqtypid, NULL) AS data_type, \
                    s.seqstart AS start, s.seqincrement AS increment, s.seqmin AS min, s.seqmax AS max, \
                    s.seqcycle AS cycle, \
                    (SELECT tc.relname::text FROM pg_depend d JOIN pg_class tc ON tc.oid = d.refobjid \
                     WHERE d.objid = c.oid AND d.classid = 'pg_class'::regclass AND d.deptype = 'a' \
                       AND d.refclassid = 'pg_class'::regclass LIMIT 1) AS owned_table, \
                    (SELECT a.attname::text FROM pg_depend d \
                     JOIN pg_attribute a ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid \
                     WHERE d.objid = c.oid AND d.classid = 'pg_class'::regclass AND d.deptype = 'a' \
                       AND d.refclassid = 'pg_class'::regclass LIMIT 1) AS owned_column \
             FROM pg_sequence s JOIN pg_class c ON c.oid = s.seqrelid \
             JOIN pg_namespace n ON n.oid = c.relnamespace \
             WHERE n.nspname = $1 AND {} \
               AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid \
                               AND d.classid = 'pg_class'::regclass AND d.deptype = 'i') \
             ORDER BY c.oid",
            not_from_extension("c.oid", "pg_class")
        ),
        schema
    );
    snap.sequences = sequences
        .into_iter()
        .map(|s| SequenceDef {
            owned_by: match (s.owned_table, s.owned_column) {
                (Some(t), Some(c)) => Some([t, c]),
                _ => None,
            },
            name: s.name,
            data_type: s.data_type,
            start: s.start,
            increment: s.increment,
            min: s.min,
            max: s.max,
            cycle: s.cycle,
        })
        .collect();
    Ok(snap)
}

impl SchemaService<'_> {
    /// Snapshot of one schema on its own read-only connection.
    pub async fn snapshot(
        &self,
        user_id: Uuid,
        connection_id: Uuid,
        schema: &str,
    ) -> AppResult<Snapshot> {
        let mut conn = self.open(user_id, connection_id).await?;
        let result = load_snapshot(&mut conn, schema).await;
        close(conn).await;
        result
    }

    /// Changes that turn the target schema into the source schema.
    pub async fn diff(&self, user_id: Uuid, req: &DiffRequest) -> AppResult<DiffResponse> {
        let (source, target) = tokio::try_join!(
            self.snapshot(user_id, req.source.connection_id, &req.source.schema),
            self.snapshot(user_id, req.target.connection_id, &req.target.schema),
        )?;
        if !source.exists {
            return Err(crate::errors::AppError::NotFound("source schema"));
        }
        let (changes, hints) = diff(&source, &target);
        Ok(DiffResponse {
            source_schema: source.schema,
            target_schema: target.schema.clone(),
            preamble: preamble(&target.schema),
            changes,
            hints,
        })
    }
}

