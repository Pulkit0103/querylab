    #[test]
    fn alters_columns_and_flags_narrowing() {
        let mut src = snap("s");
        src.tables.push(table(
            "t",
            vec![
                ColumnDef {
                    name: "id".into(),
                    data_type: "bigint".into(),
                    not_null: true,
                    ..Default::default()
                },
                ColumnDef {
                    name: "code".into(),
                    data_type: "character varying(5)".into(),
                    default: Some("'x'::character varying".into()),
                    ..Default::default()
                },
                col("added", "integer"),
            ],
        ));
        let mut tgt = snap("t");
        tgt.tables.push(table(
            "t",
            vec![
                col("id", "integer"),
                col("code", "text"),
                col("legacy", "integer"),
            ],
        ));
        let (changes, hints) = diff(&src, &tgt);
        let by_object: HashMap<&str, &Change> =
            changes.iter().map(|c| (c.object.as_str(), c)).collect();

        let id = by_object["t.id"];
        assert!(!id.destructive);
        assert_eq!(
            id.sql,
            "ALTER TABLE t.t ALTER COLUMN id TYPE bigint USING id::bigint;\n\
             ALTER TABLE t.t ALTER COLUMN id SET NOT NULL;"
        );
        assert_eq!(
            id.down_sql.as_deref(),
            Some(
                "ALTER TABLE t.t ALTER COLUMN id DROP NOT NULL;\n\
                 ALTER TABLE t.t ALTER COLUMN id TYPE integer USING id::integer;"
            )
        );
        assert!(
            by_object["t.code"].destructive,
            "text -> varchar(5) narrows"
        );
        assert!(by_object["t.code"]
            .sql
            .contains("SET DEFAULT 'x'::character varying"));
        assert_eq!(by_object["t.added"].action, ChangeAction::Create);
        let legacy = by_object["t.legacy"];
        assert!(legacy.destructive);
        assert_eq!(legacy.phase, Phase::DropColumn);
        assert_eq!(legacy.down_sql, None);
        assert!(
            hints[0].contains("RENAME COLUMN legacy TO added"),
            "{hints:?}"
        );
        // Drops come before additions.
        assert_eq!(changes[0].object, "t.legacy");
    }

    #[test]
    fn strips_the_schema_qualifier_from_definitions() {
        // Only whole qualifiers: `xs.t` and `s.t` inside an identifier stay.
        assert_eq!(
            unqualify("FOREIGN KEY (a) REFERENCES s.t(id), xs.t, other.t", "s"),
            "FOREIGN KEY (a) REFERENCES t(id), xs.t, other.t"
        );
        assert_eq!(unqualify("s.mood", "s"), "mood");
        assert_eq!(
            unqualify("CREATE INDEX i ON s.t USING btree (a)", "s"),
            "CREATE INDEX i ON t USING btree (a)"
        );
        assert_eq!(
            unqualify(
                "CREATE TRIGGER x BEFORE UPDATE ON \"My\".t FOR EACH ROW EXECUTE FUNCTION \"My\".f()",
                "My"
            ),
            "CREATE TRIGGER x BEFORE UPDATE ON t FOR EACH ROW EXECUTE FUNCTION f()"
        );
        assert_eq!(
            unqualify("CREATE INDEX i ON ONLY s.p USING btree (a)", "s"),
            "CREATE INDEX i ON ONLY p USING btree (a)"
        );
    }

    #[test]
    fn widening_rules() {
        assert!(is_widening("integer", "bigint"));
        assert!(!is_widening("bigint", "integer"));
        assert!(is_widening(
            "character varying(10)",
            "character varying(20)"
        ));
        assert!(!is_widening(
            "character varying(20)",
            "character varying(10)"
        ));
        assert!(is_widening("character varying(10)", "text"));
        assert!(is_widening("text", "character varying"));
        assert!(!is_widening("text", "character varying(5)"));
        assert!(is_widening("numeric(10,2)", "numeric(12,2)"));
        assert!(!is_widening("numeric(10,2)", "numeric(10,1)"));
        assert!(is_widening("numeric(10,2)", "numeric"));
        assert!(is_widening("integer", "numeric"));
        assert!(is_widening("real", "double precision"));
        assert!(!is_widening("timestamp without time zone", "date"));
    }

    #[test]
    fn replaces_changed_constraints_indexes_views_functions_and_triggers() {
        let con = |def: &str| ConstraintDef {
            name: "t_check".into(),
            kind: "c".into(),
            definition: def.into(),
        };
        let mut src = snap("s");
        let mut t = table("t", vec![col("id", "integer")]);
        t.constraints = vec![con("CHECK (id > 0)")];
        t.indexes = vec![IndexDef {
            name: "t_idx".into(),
            definition: "CREATE INDEX t_idx ON t USING btree (id DESC)".into(),
        }];
        src.tables.push(t.clone());
        src.views = vec![ViewDef {
            name: "v".into(),
            materialized: false,
            definition: "SELECT 2".into(),
        }];
        src.functions = vec![FunctionDef {
            name: "f".into(),
            arguments: "x integer".into(),
            kind: "function".into(),
            definition: "CREATE OR REPLACE FUNCTION f(x integer) RETURNS integer LANGUAGE sql AS $$ select 2 $$".into(),
        }];
        src.triggers = vec![TriggerDef {
            table: "t".into(),
            name: "trg".into(),
            definition: "CREATE TRIGGER trg AFTER INSERT ON t FOR EACH ROW EXECUTE FUNCTION g()"
                .into(),
        }];

        let mut tgt = snap("s");
        t.constraints = vec![con("CHECK (id >= 0)")];
        t.indexes[0].definition = "CREATE INDEX t_idx ON t USING btree (id)".into();
        tgt.tables.push(t);
        tgt.views = vec![ViewDef {
            name: "v".into(),
            materialized: false,
            definition: "SELECT 1".into(),
        }];
        tgt.functions = vec![FunctionDef {
            definition: "CREATE OR REPLACE FUNCTION f(x integer) RETURNS integer LANGUAGE sql AS $$ select 1 $$".into(),
            ..src.functions[0].clone()
        }];
        tgt.triggers = vec![TriggerDef {
            definition: "CREATE TRIGGER trg BEFORE INSERT ON t FOR EACH ROW EXECUTE FUNCTION g()"
                .into(),
            ..src.triggers[0].clone()
        }];

        let (changes, _) = diff(&src, &tgt);
        assert_eq!(
            changes.iter().map(|c| c.phase).collect::<Vec<_>>(),
            [
                Phase::DropConstraint,
                Phase::DropIndex,
                Phase::AddConstraint,
                Phase::CreateIndex,
                Phase::CreateFunction,
                Phase::CreateView,
                Phase::CreateTrigger
            ]
        );
        assert!(changes
            .iter()
            .all(|c| !c.destructive && c.down_sql.is_some()));
        assert_eq!(changes[5].sql, "CREATE OR REPLACE VIEW s.v AS\nSELECT 2;");
        assert_eq!(
            changes[5].down_sql.as_deref(),
            Some("CREATE OR REPLACE VIEW s.v AS\nSELECT 1;")
        );
        assert!(changes[4].sql.ends_with("select 2 $$;"));
        assert!(changes[6]
            .sql
            .starts_with("DROP TRIGGER trg ON s.t;\nCREATE TRIGGER trg AFTER"));
    }

