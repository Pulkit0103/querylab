//! DDL generation from introspected catalog data.
//!
//! Identifiers arrive already quoted by PostgreSQL (`quote_ident`/`%I`) and
//! expressions come from `pg_get_*def`, so this module only assembles
//! statements; it never interprets SQL.

/// A column as needed for `CREATE TABLE`.
#[derive(Debug, Clone, sqlx::FromRow)]
pub struct DdlColumn {
    /// Quoted identifier.
    pub name: String,
    pub data_type: String,
    /// Quoted, schema-qualified collation when it differs from the type default.
    pub collation: Option<String>,
    pub not_null: bool,
    /// Default expression (also the generation expression for generated columns).
    pub default_expr: Option<String>,
    /// `always` or `by_default` for identity columns.
    pub identity: Option<String>,
    /// `stored` or `virtual` for generated columns.
    pub generated: Option<String>,
    pub comment: Option<String>,
}

/// Everything needed to recreate a table.
#[derive(Debug, Clone, Default)]
pub struct DdlTable {
    /// Quoted `schema.table`.
    pub qualified: String,
    pub unlogged: bool,
    /// `pg_get_partkeydef` output for partitioned tables.
    pub partition_key: Option<String>,
    pub columns: Vec<DdlColumn>,
    /// (quoted name, `pg_get_constraintdef` output), in creation order.
    pub constraints: Vec<(String, String)>,
    /// `CREATE INDEX` statements for indexes not backing a constraint.
    pub indexes: Vec<String>,
    /// `CREATE TRIGGER` statements.
    pub triggers: Vec<String>,
    pub comment: Option<String>,
}

/// SQL string literal with standard-conforming escaping.
pub fn quote_literal(value: &str) -> String {
    format!("'{}'", value.replace('\'', "''"))
}

fn column_line(c: &DdlColumn) -> String {
    let mut line = format!("{} {}", c.name, c.data_type);
    if let Some(collation) = &c.collation {
        line.push_str(&format!(" COLLATE {collation}"));
    }
    match (
        c.generated.as_deref(),
        c.identity.as_deref(),
        &c.default_expr,
    ) {
        (Some(kind), _, Some(expr)) => {
            let storage = if kind == "virtual" {
                "VIRTUAL"
            } else {
                "STORED"
            };
            line.push_str(&format!(" GENERATED ALWAYS AS ({expr}) {storage}"));
        }
        (_, Some("always"), _) => line.push_str(" GENERATED ALWAYS AS IDENTITY"),
        (_, Some(_), _) => line.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
        (_, None, Some(expr)) => line.push_str(&format!(" DEFAULT {expr}")),
        _ => {}
    }
    if c.not_null {
        line.push_str(" NOT NULL");
    }
    line
}

/// `CREATE TABLE` plus indexes, triggers and comments, each terminated by `;`.
pub fn table_ddl(t: &DdlTable) -> String {
    let mut items: Vec<String> = t.columns.iter().map(column_line).collect();
    items.extend(
        t.constraints
            .iter()
            .map(|(name, def)| format!("CONSTRAINT {name} {def}")),
    );
    let mut out = format!(
        "CREATE {}TABLE {} (\n    {}\n)",
        if t.unlogged { "UNLOGGED " } else { "" },
        t.qualified,
        items.join(",\n    ")
    );
    if let Some(key) = &t.partition_key {
        out.push_str(&format!(" PARTITION BY {key}"));
    }
    out.push_str(";\n");

    if !t.indexes.is_empty() {
        out.push('\n');
        for index in &t.indexes {
            out.push_str(index);
            out.push_str(";\n");
        }
    }
    if !t.triggers.is_empty() {
        out.push('\n');
        for trigger in &t.triggers {
            out.push_str(trigger);
            out.push_str(";\n");
        }
    }
    let column_comments: Vec<_> = t
        .columns
        .iter()
        .filter_map(|c| c.comment.as_ref().map(|text| (c, text)))
        .collect();
    if t.comment.is_some() || !column_comments.is_empty() {
        out.push('\n');
        if let Some(comment) = &t.comment {
            out.push_str(&format!(
                "COMMENT ON TABLE {} IS {};\n",
                t.qualified,
                quote_literal(comment)
            ));
        }
        for (c, text) in column_comments {
            out.push_str(&format!(
                "COMMENT ON COLUMN {}.{} IS {};\n",
                t.qualified,
                c.name,
                quote_literal(text)
            ));
        }
    }
    out
}

/// `CREATE [MATERIALIZED] VIEW` from `pg_get_viewdef` output.
pub fn view_ddl(
    qualified: &str,
    materialized: bool,
    definition: &str,
    comment: Option<&str>,
) -> String {
    let body = definition.trim().trim_end_matches(';');
    let mut out = format!(
        "CREATE {}VIEW {} AS\n{};\n",
        if materialized { "MATERIALIZED " } else { "" },
        qualified,
        body
    );
    if let Some(comment) = comment {
        out.push_str(&format!(
            "\nCOMMENT ON {}VIEW {} IS {};\n",
            if materialized { "MATERIALIZED " } else { "" },
            qualified,
            quote_literal(comment)
        ));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn col(name: &str, ty: &str) -> DdlColumn {
        DdlColumn {
            name: name.into(),
            data_type: ty.into(),
            collation: None,
            not_null: false,
            default_expr: None,
            identity: None,
            generated: None,
            comment: None,
        }
    }

    #[test]
    fn builds_create_table_with_constraints_indexes_and_comments() {
        let mut id = col("id", "bigint");
        id.identity = Some("always".into());
        id.not_null = true;
        let mut name = col("\"Name\"", "text");
        name.collation = Some("pg_catalog.\"C\"".into());
        name.default_expr = Some("'x'::text".into());
        name.comment = Some("Display name, it's shown".into());
        let mut total = col("total", "numeric(10,2)");
        total.generated = Some("stored".into());
        total.default_expr = Some("(price * 1.2)".into());

        let ddl = table_ddl(&DdlTable {
            qualified: "inventory.products".into(),
            columns: vec![id, name, total],
            constraints: vec![
                ("products_pkey".into(), "PRIMARY KEY (id)".into()),
                ("products_price_check".into(), "CHECK (price >= 0)".into()),
            ],
            indexes: vec!["CREATE INDEX i ON inventory.products USING btree (lower(\"Name\"))".into()],
            triggers: vec!["CREATE TRIGGER t BEFORE UPDATE ON inventory.products FOR EACH ROW EXECUTE FUNCTION f()".into()],
            comment: Some("Catalogue".into()),
            ..Default::default()
        });
        assert_eq!(
            ddl,
            "CREATE TABLE inventory.products (\n    \
             id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,\n    \
             \"Name\" text COLLATE pg_catalog.\"C\" DEFAULT 'x'::text,\n    \
             total numeric(10,2) GENERATED ALWAYS AS ((price * 1.2)) STORED,\n    \
             CONSTRAINT products_pkey PRIMARY KEY (id),\n    \
             CONSTRAINT products_price_check CHECK (price >= 0)\n);\n\n\
             CREATE INDEX i ON inventory.products USING btree (lower(\"Name\"));\n\n\
             CREATE TRIGGER t BEFORE UPDATE ON inventory.products FOR EACH ROW EXECUTE FUNCTION f();\n\n\
             COMMENT ON TABLE inventory.products IS 'Catalogue';\n\
             COMMENT ON COLUMN inventory.products.\"Name\" IS 'Display name, it''s shown';\n"
        );
    }

    #[test]
    fn unlogged_partitioned_and_identity_by_default() {
        let mut id = col("id", "integer");
        id.identity = Some("by_default".into());
        let ddl = table_ddl(&DdlTable {
            qualified: "public.events".into(),
            unlogged: true,
            partition_key: Some("RANGE (created_at)".into()),
            columns: vec![id],
            ..Default::default()
        });
        assert_eq!(
            ddl,
            "CREATE UNLOGGED TABLE public.events (\n    id integer GENERATED BY DEFAULT AS IDENTITY\n) PARTITION BY RANGE (created_at);\n"
        );
    }

    #[test]
    fn view_statements() {
        assert_eq!(
            view_ddl("sales.v", false, " SELECT 1 AS x;", None),
            "CREATE VIEW sales.v AS\nSELECT 1 AS x;\n"
        );
        assert_eq!(
            view_ddl("s.m", true, "SELECT 1", Some("O'Brien")),
            "CREATE MATERIALIZED VIEW s.m AS\nSELECT 1;\n\nCOMMENT ON MATERIALIZED VIEW s.m IS 'O''Brien';\n"
        );
    }
}
