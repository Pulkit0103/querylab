-- Relationships for ER diagrams: one-to-one through a shared primary key and
-- through a unique foreign key, a composite foreign key, optional references,
-- a self-reference and a partial unique index (which does not make a
-- relationship one-to-one). Kept in their own schema so the other fixtures
-- are unchanged.

CREATE SCHEMA library;

CREATE TABLE library.authors (
    id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  text NOT NULL
);

-- One-to-one: the foreign key is the primary key.
CREATE TABLE library.author_profiles (
    author_id  integer PRIMARY KEY REFERENCES library.authors (id) ON DELETE CASCADE,
    biography  text
);

CREATE TABLE library.books (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id      integer NOT NULL REFERENCES library.authors (id),
    -- Optional one-to-many.
    translator_id  integer REFERENCES library.authors (id) ON DELETE SET NULL,
    -- Optional one-to-one self-reference.
    sequel_of      integer UNIQUE REFERENCES library.books (id),
    title          text NOT NULL
);

CREATE TABLE library.editions (
    book_id     integer NOT NULL REFERENCES library.books (id) ON DELETE CASCADE,
    edition_no  integer NOT NULL,
    published   date,
    PRIMARY KEY (book_id, edition_no)
);

-- Composite foreign key: many copies per edition.
CREATE TABLE library.copies (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id     integer NOT NULL,
    edition_no  integer NOT NULL,
    barcode     text NOT NULL UNIQUE,
    CONSTRAINT copies_edition_fkey FOREIGN KEY (book_id, edition_no)
        REFERENCES library.editions (book_id, edition_no)
);

-- Only one open loan per copy, but closed loans repeat: still one-to-many.
CREATE TABLE library.loans (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    copy_id      integer NOT NULL REFERENCES library.copies (id),
    borrowed_on  date NOT NULL DEFAULT current_date,
    returned_on  date
);
CREATE UNIQUE INDEX loans_open_copy_key ON library.loans (copy_id) WHERE returned_on IS NULL;

