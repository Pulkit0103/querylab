import { defineConfig, devices } from "@playwright/test";

/**
 * Browser end-to-end tests against a running stack: the Rust API (with a
 * metadata database) behind this Next.js app. `E2E_BASE_URL` points at an
 * already running frontend; otherwise the production build is started.
 *
 * `E2E_DATABASE_URL` is the PostgreSQL database the tests connect to as a
 * target; the API must allow private networks to reach it locally.
 */
const baseURL = process.env.E2E_BASE_URL ?? "http://localhost:3000";

export default defineConfig({
  testDir: "./e2e",
  fullyParallel: false,
  forbidOnly: !!process.env.CI,
  retries: process.env.CI ? 1 : 0,
  workers: 1,
  reporter: process.env.CI ? [["github"], ["html", { open: "never" }]] : "list",
  timeout: 60_000,
  expect: { timeout: 15_000 },
  use: {
    baseURL,
    trace: "retain-on-failure",
    screenshot: "only-on-failure",
  },
  projects: [{ name: "chromium", use: { ...devices["Desktop Chrome"], viewport: { width: 1440, height: 900 } } }],
  webServer: process.env.E2E_BASE_URL
    ? undefined
    : {
        command: "npm run start",
        url: baseURL,
        reuseExistingServer: !process.env.CI,
        timeout: 120_000,
      },
});
